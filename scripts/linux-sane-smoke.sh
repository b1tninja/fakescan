#!/usr/bin/env bash
# Linux SANE / sane-airscan smoke against a running fakescan (:3920).
# Listing + open are required. One-page acquire is best-effort (documents SOAP gaps).
set -euo pipefail

BASE_URL="${FAKESCAN_URL:-http://127.0.0.1:3920}"
SOAP_URL="${BASE_URL%/}/ScannerService"
DEVICE_NAME="${SANE_DEVICE_NAME:-fakescan}"
OUT_DIR="${SMOKE_OUT_DIR:-/tmp/fakescan-sane-smoke}"
ACQUIRE_REQUIRED="${ACQUIRE_REQUIRED:-0}"
CONF_DIR="${SANE_CONFIG_DIR:-/tmp/fakescan-sane-conf}"

log() { printf '+ %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "missing command: $1 (install sane-utils / sane-airscan)"
}

wait_health() {
  local i
  for i in $(seq 1 60); do
    if curl -fsS "${BASE_URL}/health" >/dev/null 2>&1; then
      log "health ok (${BASE_URL})"
      return 0
    fi
    sleep 1
  done
  die "fakescan not healthy at ${BASE_URL}/health"
}

write_airscan_conf() {
  mkdir -p "${CONF_DIR}/dll.d"
  # Prefer our conf; still need dll.d so the airscan backend loads when
  # SANE_CONFIG_DIR replaces /etc/sane.d for some lookups.
  if [[ -f /etc/sane.d/dll.conf ]]; then
    cp /etc/sane.d/dll.conf "${CONF_DIR}/dll.conf"
  else
    printf 'airscan\n' >"${CONF_DIR}/dll.conf"
  fi
  if [[ -d /etc/sane.d/dll.d ]]; then
    cp -a /etc/sane.d/dll.d/. "${CONF_DIR}/dll.d/" 2>/dev/null || true
  fi
  if ! grep -qrE '^[[:space:]]*airscan([[:space:]]|$)' "${CONF_DIR}/dll.conf" "${CONF_DIR}/dll.d" 2>/dev/null; then
    printf 'airscan\n' >"${CONF_DIR}/dll.d/airscan"
  fi

  cat >"${CONF_DIR}/airscan.conf" <<EOF
# Generated by linux-sane-smoke.sh — manual WSD URL (no WS-Discovery).
[options]
discovery = disable

[devices]
${DEVICE_NAME} = ${SOAP_URL}, WSD
EOF

  export SANE_CONFIG_DIR="${CONF_DIR}"
  # Env override (when supported by the installed sane-airscan); config is the reliable path.
  export SANE_AIRSCAN_DEVICE="wsd:${DEVICE_NAME}:${SOAP_URL}"
  log "wrote ${CONF_DIR}/airscan.conf"
  log "SANE_CONFIG_DIR=${SANE_CONFIG_DIR}"
  log "SANE_AIRSCAN_DEVICE=${SANE_AIRSCAN_DEVICE}"
}

need_cmd curl
need_cmd scanimage
wait_health
write_airscan_conf

log "control status"
curl -fsS "${BASE_URL}/v1/status"
echo

log "load one page"
curl -fsS -X POST "${BASE_URL}/v1/pages" \
  -H 'content-type: application/json' \
  -d '{"count":1}'
echo

log "scanimage -L"
LIST_OUT="$(scanimage -L 2>&1 || true)"
printf '%s\n' "$LIST_OUT"
# Ubuntu airscan names manual devices like airscan:w0:fakescan
DEVICE_SPEC="$(printf '%s\n' "$LIST_OUT" | sed -n "s/^device \`\\(airscan:[^']*${DEVICE_NAME}[^']*\\)'.*$/\\1/p" | head -1)"
if [[ -z "${DEVICE_SPEC}" ]]; then
  DEVICE_SPEC="$(printf '%s\n' "$LIST_OUT" | sed -n "s/^device \`\\(airscan:[^']*\\)'.*$/\\1/p" | head -1)"
fi
[[ -n "${DEVICE_SPEC}" ]] || die "scanimage -L did not list an airscan device for ${DEVICE_NAME}"
log "using device ${DEVICE_SPEC}"

log "open device (scanimage -A)"
OPTS_OUT="$(scanimage -d "${DEVICE_SPEC}" -A 2>&1 || true)"
printf '%s\n' "$OPTS_OUT"
if ! echo "$OPTS_OUT" | grep -qiE 'All options specific to device|Options specific to device'; then
  die "could not open ${DEVICE_SPEC} / read options"
fi
if echo "$OPTS_OUT" | grep -qiE 'failed to open device|Invalid argument'; then
  if ! echo "$OPTS_OUT" | grep -qiE 'All options specific to device|Options specific to device'; then
    die "could not open ${DEVICE_SPEC}"
  fi
fi
log "device open ok"

mkdir -p "$OUT_DIR"
OUT_PNG="${OUT_DIR}/page.png"
rm -f "$OUT_PNG"

log "acquire one page -> ${OUT_PNG}"
set +e
ACQUIRE_LOG="$(scanimage -d "${DEVICE_SPEC}" --format=png -o "$OUT_PNG" 2>&1)"
ACQUIRE_RC=$?
set -e
printf '%s\n' "$ACQUIRE_LOG"

if [[ $ACQUIRE_RC -eq 0 && -s "$OUT_PNG" ]]; then
  log "acquire ok ($(wc -c <"$OUT_PNG") bytes)"
  if command -v file >/dev/null 2>&1; then
    file "$OUT_PNG" || true
  fi
  echo "SMOKE_RESULT list=ok open=ok acquire=ok"
  exit 0
fi

log "acquire failed (rc=${ACQUIRE_RC}); listing/open still ok"
cat <<'EOF'
SOAP / acquire gap notes:
  fakescan implements GetScannerElements, ValidateScanTicket, CreateScanJob,
  RetrieveImage (MTOM), CancelJob, and a minimal WS-Transfer Get.
  If scanimage listed and opened the device but could not transfer a page,
  re-run with SANE_DEBUG_AIRSCAN=4 and compare Action= lines to the stubs in
  crates/fakescan/src/wsd/mod.rs (e.g. GetJobElements, GetJobHistory, or
  stricter CreateScanJob / MTOM expectations).
EOF

if [[ "$ACQUIRE_REQUIRED" == "1" ]]; then
  die "acquire required (ACQUIRE_REQUIRED=1) but failed"
fi

echo "SMOKE_RESULT list=ok open=ok acquire=fail"
exit 0
